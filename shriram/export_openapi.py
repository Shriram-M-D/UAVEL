"""Regenerate docs/api/openapi.yaml from the FastAPI app (Skanda generates his typed client from it)."""
import os, sys, tempfile
from pathlib import Path

import yaml

os.environ["UAV_NO_APP"] = "1"
HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
from uav_backend.api import create_app  # noqa: E402
from uav_backend.config import ExperimentConfig  # noqa: E402
from uav_backend.core import Backend  # noqa: E402

tmp = Path(tempfile.mkdtemp())
cfg = ExperimentConfig()
cfg.backend.db_path, cfg.backend.artefact_dir = str(tmp / "x.sqlite"), str(tmp / "a")
spec = create_app(Backend(cfg)).openapi()
out = HERE.parent / "docs" / "api" / "openapi.yaml"
out.write_text("# GENERATED by shriram/export_openapi.py - do not edit by hand\n" + yaml.safe_dump(spec, sort_keys=False))
print("wrote", out)
